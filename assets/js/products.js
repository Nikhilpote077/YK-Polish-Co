  const palettes = {
    pink: ["#f6c5cf", "#c982a2"],
    purple: ["#d9c9ef", "#8e72c5"],
    nude: ["#f1ddd0", "#b88978"],
    red: ["#c33d58", "#641b35"],
    black: ["#4b4550", "#151219"],
    blue: ["#a9d5e8", "#4e77a5"],
    green: ["#c8d8bd", "#6d8562"],
  };
  const key = product.colours[0] || "pink";
  const p = palettes[key];
